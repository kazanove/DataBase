<?php

declare(strict_types=1);

namespace CodeX\DataBase\Dialect;

use CodeX\Contract\DataBase\Sql;

/**
 * SQL-диалект для СУБД Firebird.
 *
 * Особенности:
 * - Пагинация через FIRST / SKIP (классический синтаксис)
 * - Поддержка RETURNING для INSERT, UPDATE, DELETE
 * - Блокировка через FOR UPDATE WITH LOCK
 * - Идентификаторы экранируются двойными кавычками
 *
 * @see https://www.php.net/manual/ru/ref.pdo-firebird.php
 */
class Firebird implements Sql
{
    /**
     * Построение пагинации для Firebird.
     *
     * Используется классический синтаксис:
     *   SELECT FIRST 10 SKIP 5 ...
     *
     * Для Firebird 3.0+ также доступен стандартный синтаксис:
     *   OFFSET 5 ROWS FETCH FIRST 10 ROWS ONLY
     * Однако FIRST / SKIP обеспечивает совместимость со всеми версиями.
     */
    public function buildLimitOffset(?int $limit, ?int $offset): string
    {
        $sql = '';

        if ($limit !== null) {
            $sql .= 'FIRST ' . $limit;
        }

        if ($offset !== null) {
            $sql .= ' SKIP ' . $offset;
        }

        return $sql;
    }

    /**
     * Построение блокировки строк.
     *
     * Firebird поддерживает только FOR UPDATE с опциональным WITH LOCK.
     * Аналога FOR SHARE в Firebird не существует.
     */
    public function buildLock(bool $forUpdate, bool $forShare): string
    {
        if ($forUpdate) {
            return 'WITH LOCK';
        }

        // Firebird не поддерживает разделяемые блокировки (FOR SHARE)
        return '';
    }

    /**
     * Экранирование идентификаторов.
     *
     * В Firebird идентификаторы заключаются в двойные кавычки.
     * Двойные кавычки внутри идентификатора экранируются удвоением.
     */
    public function quoteIdentifier(string $identifier): string
    {
        return '"' . str_replace('"', '""', $identifier) . '"';
    }

    /**
     * Генерация имени именованного плейсхолдера.
     *
     * Пример: :w_0, :in_1, :ins_2
     */
    public function getPlaceholderName(string $baseName, int $counter): string
    {
        return ':' . $baseName . '_' . $counter;
    }

    /**
     * Префикс для плейсхолдеров.
     */
    public function getPlaceholderPrefix(): string
    {
        return ':';
    }

    /**
     * Firebird поддерживает предложение RETURNING.
     *
     * Пример:
     *   INSERT INTO users (name) VALUES ('test') RETURNING id;
     */
    public function supportsReturning(): bool
    {
        return true;
    }

    /**
     * Построение предложения RETURNING.
     */
    public function buildReturning(string $table, array $columns): string
    {
        if ($columns === []) {
            return '';
        }

        $quoted = array_map([$this, 'quoteIdentifier'], $columns);

        return 'RETURNING ' . implode(', ', $quoted);
    }

    /**
     * Экранирование строковых значений.
     *
     * Одинарные кавычки экранируются удвоением.
     */
    public function quoteString(string $value): string
    {
        return '\'' . str_replace('\'', '\'\'', $value) . '\'';
    }
    public function getAutoIncrementKeyword(): string
    {
        return 'GENERATED BY DEFAULT AS IDENTITY';
    }

    public function getAutoIncrementType(string $baseType): string
    {
        return $baseType;
    }

    public function supportsUnsigned(): bool
    {
        return false;
    }

    public function dropForeignKey(string $name): string
    {
        return 'DROP CONSTRAINT ' . $this->quoteIdentifier($name);
    }
    public function buildDecimalType(int $precision, int $scale): string
    {
        return 'DECIMAL(' . $precision . ', ' . $scale . ')';
    }
}